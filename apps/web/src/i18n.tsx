const dicts: Record<Lang, Record<Key, string>> = { he, en };

interface I18n {
  lang: Lang;
  setLang(l: Lang): void;
  t(key: Key, vars?: Record<string, string | number>): string;
  locale: string;
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children, initial }: { children: ReactNode; initial?: Lang }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return (localStorage.getItem('finc.lang') as Lang | null) ?? initial ?? 'he';
    } catch {
      return initial ?? 'he';
    }
  });
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'he' ? 'rtl' : 'ltr';
  }, [lang]);
  const value = useMemo<I18n>(
    () => ({
      lang,
      locale: lang === 'he' ? 'he-IL' : 'en-GB',
      setLang(l) {
        setLangState(l);
        try {
          localStorage.setItem('finc.lang', l);
        } catch {
          /* ignore */
        }
      },
      t(key, vars) {
        let s: string = dicts[lang][key] ?? he[key] ?? key;
        if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
        return s;
      },
    }),
    [lang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('I18nProvider missing');
  return v;
}
